def main() -> int:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    SPLIT_PATH.parent.mkdir(parents=True, exist_ok=True)
    PROVENANCE_PATH.parent.mkdir(parents=True, exist_ok=True)

    split_lines: list[str] = []
    for case in CASES:
        scenario = scenario_from_case(case)
        out_path = OUT_DIR / f"{case['scenario_id']}.yaml"
        with out_path.open("w", encoding="utf-8") as handle:
            yaml.safe_dump(scenario, handle, sort_keys=False, allow_unicode=False, width=100)
        split_lines.append(str(out_path))

    SPLIT_PATH.write_text("\n".join(split_lines) + "\n", encoding="utf-8")

    with PROVENANCE_PATH.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(
            handle,
            fieldnames=[
                "scenario_id",
                "case_name",
                "source_kind",
                "source_url",
                "grounding_notes",
                "syntheticized_fields",
            ],
        )
        writer.writeheader()
        for case in CASES:
            writer.writerow(
                {
                    "scenario_id": case["scenario_id"],
                    "case_name": case["case_name"],
                    "source_kind": case["source_kind"],
                    "source_url": case["source_url"],
                    "grounding_notes": case["grounding_notes"],
                    "syntheticized_fields": "party names; settlement values; role files; private knowledge split; offers; dialogue; forbidden assertion traps",
                }
            )
    return 0


